/**
 * Submit an 837P claim to the clearinghouse.
 * Returns a tracking ID and initial status.
 */
async function submitClaim(claim, provider, payer) {
  const edi837 = build837P(claim, provider, payer);
  const trackingId = `CLR-${Date.now()}-${crypto.randomBytes(3).toString('hex').toUpperCase()}`;

  if (!isConfigured()) {
    return {
      success:     true,
      demo:        true,
      trackingId,
      status:      'accepted',
      statusCode:  'A',
      message:     'Claim accepted by clearinghouse (demo mode)',
      edi837,
      submittedAt: new Date().toISOString(),
      estimatedPaymentDate: new Date(Date.now() + 14 * 86400000).toISOString(),
    };
  }

  try {
    const res = await makeRequest('POST', '/claims/submit', {
      format:    'EDI_837P',
      content:   edi837,
      claimId:   claim.id,
      senderId:  SENDER_ID,
    });

    return {
      success:     res.status < 300,
      trackingId:  res.body?.trackingId || trackingId,
      status:      res.body?.status     || 'pending',
      statusCode:  res.body?.statusCode || 'P',
      message:     res.body?.message    || 'Submitted',
      edi837,
      rawResponse: res.body,
      submittedAt: new Date().toISOString(),
    };
  } catch (err) {
    return { success: false, error: err.message, trackingId };
  }
}

/**
 * Check the status of a previously submitted claim (EDI 276).
 */
async function getClaimStatus(trackingId) {
  if (!isConfigured()) {
    const statuses = ['accepted', 'in_process', 'finalized_paid', 'finalized_denied'];
    return {
      success:    true,
      demo:       true,
      trackingId,
      status:     statuses[Math.floor(Date.now() / 10000) % statuses.length],
      lastUpdated: new Date().toISOString(),
    };
  }

  try {
    const res = await makeRequest('GET', `/claims/${trackingId}/status`);
    return { success: res.status < 300, trackingId, ...res.body };
  } catch (err) {
    return { success: false, error: err.message, trackingId };
  }
}

/**
 * Retrieve 835 ERA files from the clearinghouse.
 * Returns parsed payment data.
 */
async function getERAs({ fromDate, toDate, limit = 20 } = {}) {
  if (!isConfigured()) {
    return {
      success: true,
      demo:    true,
      eras: [{
        eraId:        'ERA-DEMO-001',
        checkNumber:  'CHK-00001',
        payerName:    'Aetna Health Plans',
        totalPaid:    4250.00,
        claimCount:   8,
        receivedAt:   new Date().toISOString(),
        payments: [
          { claimId: 'CLM-001', paidAmount: 720.00,  claimAmount: 850.00,  status: 'paid' },
          { claimId: 'CLM-002', paidAmount: 0,        claimAmount: 350.00,  status: 'denied', reasonCode: 'CO-18' },
          { claimId: 'CLM-003', paidAmount: 1100.00, claimAmount: 1200.00, status: 'adjusted', reasonCode: 'CO-45' },
        ],
      }],
    };
  }

  try {
    const params = new URLSearchParams({ limit });
    if (fromDate) { params.set('from', fromDate); }
    if (toDate)   { params.set('to', toDate); }
    const res = await makeRequest('GET', `/eras?${params.toString()}`);

    const eras = (res.body?.eras || []).map((era) => ({
      ...era,
      parsed: era.content ? parse835ERA(era.content) : null,
    }));

    return { success: res.status < 300, eras };
  } catch (err) {
    return { success: false, error: err.message, eras: [] };
  }
}

